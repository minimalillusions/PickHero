"""German. The reference catalogue: every key the app uses exists here.

Two rules, and both have bitten this app already:

  A value is a WHOLE SENTENCE, never a fragment. Word order and agreement
  differ between languages, so a sentence assembled from pieces cannot be
  translated. If you find yourself writing t(...) + something, the catalogue
  needs another key, not another fragment.

  Note names are NOT here on purpose. German convention writes B as H, but
  every Guitar Pro file, every tuner and every tab online uses the scientific
  names, and the app has to agree with the material the player learns from.
"""

